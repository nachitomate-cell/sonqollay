function cons(
  ok: Partial<Record<string, boolean>>,
  respMap: Record<string, string>
) {
  const labels: Record<string, string> = {
    ingenieria: "Ingeniería IFC",
    materiales: "Materiales en obra",
    equipos: "Equipos / herramientas",
    manoObra: "Mano de obra",
    permisos: "Permisos / RDT",
    seguridad: "Análisis de riesgo",
    accesos: "Acceso al área",
    qaQc: "Plan QA/QC",
  };
  return Object.keys(labels).map((k) => ({
    key: k as any,
    label: labels[k],
    ok: !!ok[k],
    responsable: respMap[k] ?? "—",
    fechaCompromiso: today,
  }));
}

